#!/usr/bin/env python3
"""Regenerate tools/graphify/requirements.txt with hashes (copied from Iranux-Bash-Runner, where it was written).

CoCo VPN builds the graph on ubuntu-latest; the Windows-resolved set below also installs there (checked on
CPython 3.13, Linux x64), because every file PyPI serves for each release is hashed.

Resolves the dependency set of the pinned graphifyy release for CPython on Windows x64 (the CI
runners) with ``pip download`` (wheels only, nothing is installed or executed), then writes one
``name==version --hash=sha256:...`` entry per package with the hashes of every file PyPI serves
for that release, so the pin holds on any platform and Python build. When a package resolves to a
different version on one of the Python versions, each gets an environment marker.

    python3 -I tools/graphify/pin.py 0.9.108            # writes tools/graphify/requirements.txt
    python3 -I tools/graphify/pin.py 0.9.108 --check    # exits 1 when the file would change

Needs network access to pypi.org and files.pythonhosted.org. Python versions covered: 3.11 to 3.14.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from collections import defaultdict
from pathlib import Path

PYTHON_VERSIONS = ("3.11", "3.12", "3.13", "3.14")
HERE = Path(__file__).resolve().parent
TARGET = HERE / "requirements.txt"
HEADER = """\
# Graphify (https://github.com/Graphify-Labs/graphify): the code knowledge graph in graphify-out/.
# Generated by tools/graphify/pin.py; do not edit by hand. Every package carries the sha256 of all
# files PyPI serves for that release, so `pip install --require-hashes` refuses anything else.
"""


def resolve(version: str, python: str) -> dict[str, str]:
    """Return {package: version} that pip picks for graphifyy==version on win_amd64 / CPython python."""
    abi = "cp" + python.replace(".", "")
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [sys.executable, "-m", "pip", "download", "--quiet", "--only-binary=:all:",
             "--platform", "win_amd64", "--python-version", python, "--implementation", "cp",
             "--abi", abi, "--abi", "none", "--dest", tmp, f"graphifyy=={version}"],
            check=True,
        )
        found: dict[str, str] = {}
        for wheel in Path(tmp).glob("*.whl"):
            name, ver = wheel.name.split("-")[:2]
            found[name.lower().replace("_", "-")] = ver
    return found


def hashes(package: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{package}/{version}/json", timeout=60) as r:
        data = json.load(r)
    digests = sorted({f["digests"]["sha256"] for f in data["urls"] if not f.get("yanked")})
    if not digests:
        raise SystemExit(f"no files on PyPI for {package}=={version}")
    return digests


def render(version: str) -> str:
    per_python = {py: resolve(version, py) for py in PYTHON_VERSIONS}
    # package -> version -> [python versions]
    choices: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for py, found in per_python.items():
        for package, ver in found.items():
            choices[package][ver].append(py)
    lines = [HEADER]
    for package in sorted(choices):
        for ver, pys in sorted(choices[package].items()):
            marker = ""
            if len(pys) < len(PYTHON_VERSIONS):
                marker = " ; " + " or ".join(f'python_version == "{py}"' for py in pys)
            lines.append(f"{package}=={ver}{marker} \\")
            lines.extend(f"    --hash=sha256:{h} \\" for h in hashes(package, ver))
            lines[-1] = lines[-1][:-2]
    return "\n".join(lines) + "\n"


def main() -> None:
    args = sys.argv[1:]
    check = "--check" in args
    positional = [a for a in args if not a.startswith("--")]
    if len(positional) != 1 or not re.fullmatch(r"\d+\.\d+\.\d+", positional[0]):
        raise SystemExit(__doc__)
    text = render(positional[0])
    if check:
        if TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{TARGET} is out of date; run tools/graphify/pin.py")
        print(f"{TARGET} is current")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({text.count('==')} pins)")


if __name__ == "__main__":
    main()
